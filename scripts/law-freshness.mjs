#!/usr/bin/env node
// ============================================================================
// npm run law:freshness — list law facts that need (re)verification.
//
// Lists every fact in lib/data/jurisdictions.js and every item in
// lib/data/regulatory-updates.js that is either unverified (no primary source)
// or verified more than VERIFICATION_WINDOW_DAYS (90) days ago.
//
//   npm run law:freshness                 plain text
//   npm run law:freshness -- --markdown   markdown (used for the weekly issue)
//   npm run law:freshness -- --json       JSON
//   npm run law:freshness -- --check      exit 1 when anything is listed
//   --now=YYYY-MM-DD                      evaluate as of another date
// ============================================================================

import JURISDICTIONS from "../lib/data/jurisdictions.js";
import REGULATORY_UPDATES from "../lib/data/regulatory-updates.js";
import { listFreshnessIssues, VERIFICATION_WINDOW_DAYS } from "../lib/law/provenance.js";

const args = process.argv.slice(2);
const nowArg = args.find((a) => a.startsWith("--now="));
const now = nowArg ? new Date(`${nowArg.slice(6)}T00:00:00Z`) : new Date();
if (Number.isNaN(now.getTime())) {
  console.error(`Invalid --now date: ${nowArg}`);
  process.exit(2);
}

const issues = listFreshnessIssues(JURISDICTIONS, REGULATORY_UPDATES, now);
const stale = issues.filter((i) => i.reason === "stale");
const unverified = issues.filter((i) => i.reason === "unverified");
const asOf = now.toISOString().slice(0, 10);

function age(i) {
  return i.daysSinceVerified === null ? "never" : `${i.lastVerified} (${i.daysSinceVerified} days ago)`;
}

if (args.includes("--json")) {
  console.log(JSON.stringify({ asOf, windowDays: VERIFICATION_WINDOW_DAYS, count: issues.length, issues }, null, 2));
} else if (args.includes("--markdown")) {
  const out = [];
  out.push(`Law data freshness report as of **${asOf}** (verification window: ${VERIFICATION_WINDOW_DAYS} days).`);
  out.push("");
  out.push(`- Past the verification window: **${stale.length}**`);
  out.push(`- Never verified against a primary source: **${unverified.length}**`);
  out.push("");
  out.push("The app shows unverified figures as \"Verify with counsel / source pending\" and tells the chat model not to state them. To clear an item, check it against the primary source (DOL, EEOC, state labor department, statute site), then update `value`, `sourceUrl`, `effectiveDate`, `lastVerified` and `verification` in `lib/data/jurisdictions.js` or `lib/data/regulatory-updates.js`.");
  const table = (title, rows) => {
    if (rows.length === 0) return;
    out.push("", `### ${title}`, "", "| Item | Jurisdiction | Last verified | Source |", "|---|---|---|---|");
    for (const i of rows) {
      out.push(`| \`${i.id}\` ${i.field.startsWith("update:") ? i.field.slice(8).replace(/\|/g, "/") : ""} | ${i.jurisdiction} | ${age(i)} | ${i.sourceUrl || "pending"} |`);
    }
  };
  table("Past the verification window", stale);
  table("Unverified", unverified);
  if (issues.length === 0) out.push("", "Nothing to re-verify.");
  out.push("", "_Generated by `npm run law:freshness -- --markdown`._");
  console.log(out.join("\n"));
} else {
  console.log(`Law data freshness as of ${asOf} (window ${VERIFICATION_WINDOW_DAYS} days): ${stale.length} stale, ${unverified.length} unverified.`);
  for (const i of issues) {
    console.log(`  [${i.reason}] ${i.id}  last verified: ${age(i)}${i.sourceUrl ? `  ${i.sourceUrl}` : ""}`);
  }
}

if (args.includes("--check") && issues.length > 0) process.exit(1);
